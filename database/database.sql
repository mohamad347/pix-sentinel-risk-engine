CREATE TYPE pix_analysis_status AS ENUM (
    'approved',
    'two_factor_required',
    'rejected'
);

CREATE TABLE accounts(
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant                     VARCHAR(64),
    branch                          VARCHAR(64) NOT NULL,
    account_number                  VARCHAR(64) NOT NULL,
    owner_document                  VARCHAR(64) NOT NULL,
    opening_at                      TIMESTAMPTZ NOT NULL,
    CONSTRAINT accounts_identity_key
        UNIQUE NULLS NOT DISTINCT (
            participant,
            branch,
            account_number,
            owner_document
        ),
    CONSTRAINT ck_accounts_participant_not_blank
        CHECK (participant IS NULL OR btrim(participant) <> ''),
    CONSTRAINT ck_accounts_branch_not_blank CHECK (btrim(branch) <> ''),
    CONSTRAINT ck_accounts_number_not_blank CHECK (btrim(account_number) <> ''),
    CONSTRAINT ck_accounts_document_not_blank CHECK (btrim(owner_document) <> '')
);

CREATE TABLE devices(
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifier                      VARCHAR(128) NOT NULL,
    CONSTRAINT devices_identifier_key UNIQUE (identifier),
    CONSTRAINT ck_devices_identifier_not_blank CHECK (btrim(identifier) <> '')
);

CREATE TABLE pix_transactions(
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id                     VARCHAR(128) NOT NULL,
    request_fingerprint             CHAR(64) NOT NULL,
    canonicalization_version        VARCHAR(32) NOT NULL,
    request_payload                 JSONB NOT NULL,
    amount_cents                    BIGINT NOT NULL,
    transaction_at                  TIMESTAMPTZ NOT NULL,
    received_at                     TIMESTAMPTZ NOT NULL,
    payer_account_id                BIGINT NOT NULL,
    payee_account_id                BIGINT NOT NULL,
    device_id                       BIGINT NOT NULL,
    source_channel                  VARCHAR(32) NOT NULL,
    source_ip                       INET NOT NULL,
    source_latitude                 DOUBLE PRECISION,
    source_longitude                DOUBLE PRECISION,
    CONSTRAINT pix_transactions_external_id_key UNIQUE (external_id),
    CONSTRAINT fk_pix_transactions_payer_account
        FOREIGN KEY (payer_account_id) REFERENCES accounts(id) ON DELETE RESTRICT,
    CONSTRAINT fk_pix_transactions_payee_account
        FOREIGN KEY (payee_account_id) REFERENCES accounts(id) ON DELETE RESTRICT,
    CONSTRAINT fk_pix_transactions_device
        FOREIGN KEY (device_id) REFERENCES devices(id) ON DELETE RESTRICT,
    CONSTRAINT ck_pix_transactions_positive_amount CHECK (amount_cents > 0),
    CONSTRAINT ck_pix_transactions_payload_object
        CHECK (jsonb_typeof(request_payload) = 'object'),
    CONSTRAINT ck_pix_transactions_channel_not_blank
        CHECK (btrim(source_channel) <> ''),
    CONSTRAINT ck_pix_transactions_geolocation_pair
        CHECK ((source_latitude IS NULL) = (source_longitude IS NULL)),
    CONSTRAINT ck_pix_transactions_latitude_range
        CHECK (source_latitude IS NULL OR source_latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_pix_transactions_longitude_range
        CHECK (source_longitude IS NULL OR source_longitude BETWEEN -180 AND 180)
);

CREATE TABLE pix_analyses(
    analysis_key                    UUID PRIMARY KEY,
    transaction_id                  BIGINT NOT NULL,
    status                          pix_analysis_status NOT NULL,
    metadata                        JSONB NOT NULL,
    evidence_snapshot               JSONB NOT NULL,
    policy_version                  VARCHAR(64) NOT NULL,
    evaluated_at                    TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_pix_analyses_transaction
        FOREIGN KEY (transaction_id) REFERENCES pix_transactions(id) ON DELETE RESTRICT,
    CONSTRAINT pix_analyses_transaction_id_key UNIQUE (transaction_id),
    CONSTRAINT ck_pix_analyses_metadata_object
        CHECK (jsonb_typeof(metadata) = 'object'),
    CONSTRAINT ck_pix_analyses_evidence_object
        CHECK (jsonb_typeof(evidence_snapshot) = 'object')
);

CREATE INDEX ix_pix_transactions_payer_received_at
    ON pix_transactions (payer_account_id, received_at);

CREATE INDEX ix_pix_transactions_payee_received_at
    ON pix_transactions (payee_account_id, received_at);

CREATE INDEX ix_pix_transactions_device_received_at
    ON pix_transactions (device_id, received_at);

CREATE INDEX ix_pix_transactions_source_ip_received_at
    ON pix_transactions (source_ip, received_at);
