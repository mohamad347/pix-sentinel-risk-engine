CREATE TABLE pix_transactions(
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id                     TEXT NOT NULL UNIQUE,
    request_fingerprint             CHAR(64) NOT NULL,
    request_payload                 JSONB NOT NULL,
    amount_cents                    BIGINT NOT NULL CHECK (amount_cents > 0),
    transaction_at                  TIMESTAMPTZ NOT NULL,
    received_at                     TIMESTAMPTZ NOT NULL,
    payer_document                  TEXT NOT NULL,
    payer_branch                    TEXT NOT NULL,
    payer_account_number            TEXT NOT NULL,
    payee_participant               TEXT NOT NULL,
    payee_branch                    TEXT NOT NULL,
    payee_account_number            TEXT NOT NULL,
    payee_document                  TEXT NOT NULL,
    source_device_id                TEXT NOT NULL
);

CREATE TABLE pix_analyses(
    analysis_key                    UUID PRIMARY KEY,
    transaction_id                  BIGINT NOT NULL UNIQUE REFERENCES pix_transactions(id),
    status                          TEXT NOT NULL CHECK (status IN ('approved', 'two_factor_required', 'rejected')),
    metadata                        JSONB NOT NULL CHECK (jsonb_typeof(metadata) = 'object'),
    evidence_snapshot               JSONB NOT NULL CHECK (jsonb_typeof(evidence_snapshot) = 'object'),
    policy_version                  TEXT NOT NULL,
    evaluated_at                    TIMESTAMPTZ NOT NULL
);
