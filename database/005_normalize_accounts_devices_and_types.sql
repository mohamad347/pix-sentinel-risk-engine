-- Upgrade manual para bancos criados antes da normalização em quatro entidades.
-- Faça backup e execute em janela de manutenção: o script reescreve índices e
-- converte o IP histórico para o tipo nativo INET.

BEGIN;

DO $$
BEGIN
    CREATE TYPE pix_analysis_status AS ENUM (
        'approved',
        'two_factor_required',
        'rejected'
    );
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;

LOCK TABLE pix_transactions, pix_analyses IN ACCESS EXCLUSIVE MODE;

CREATE TABLE IF NOT EXISTS accounts(
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant                     VARCHAR(64),
    branch                          VARCHAR(64) NOT NULL,
    account_number                  VARCHAR(64) NOT NULL,
    owner_document                  VARCHAR(64) NOT NULL,
    opening_at                      TIMESTAMPTZ NOT NULL,
    CONSTRAINT accounts_identity_key
        UNIQUE NULLS NOT DISTINCT (
            participant,
            branch,
            account_number,
            owner_document
        ),
    CONSTRAINT ck_accounts_participant_not_blank
        CHECK (participant IS NULL OR btrim(participant) <> ''),
    CONSTRAINT ck_accounts_branch_not_blank CHECK (btrim(branch) <> ''),
    CONSTRAINT ck_accounts_number_not_blank CHECK (btrim(account_number) <> ''),
    CONSTRAINT ck_accounts_document_not_blank CHECK (btrim(owner_document) <> '')
);

CREATE TABLE IF NOT EXISTS devices(
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifier                      VARCHAR(128) NOT NULL,
    CONSTRAINT devices_identifier_key UNIQUE (identifier),
    CONSTRAINT ck_devices_identifier_not_blank CHECK (btrim(identifier) <> '')
);

INSERT INTO accounts (participant, branch, account_number, owner_document, opening_at)
SELECT DISTINCT
    NULL,
    payer_branch,
    payer_account_number,
    upper(translate(payer_document, '.-/ ', '')),
    (request_payload #>> '{source_account,opening_date}')::TIMESTAMPTZ
FROM pix_transactions
ON CONFLICT ON CONSTRAINT accounts_identity_key DO NOTHING;

INSERT INTO accounts (participant, branch, account_number, owner_document, opening_at)
SELECT DISTINCT
    payee_participant,
    payee_branch,
    payee_account_number,
    upper(translate(payee_document, '.-/ ', '')),
    (request_payload #>> '{destination_account,opening_date}')::TIMESTAMPTZ
FROM pix_transactions
ON CONFLICT ON CONSTRAINT accounts_identity_key DO NOTHING;

INSERT INTO devices (identifier)
SELECT DISTINCT source_device_id
FROM pix_transactions
ON CONFLICT ON CONSTRAINT devices_identifier_key DO NOTHING;

ALTER TABLE pix_transactions
    ADD COLUMN IF NOT EXISTS payer_account_id BIGINT,
    ADD COLUMN IF NOT EXISTS payee_account_id BIGINT,
    ADD COLUMN IF NOT EXISTS device_id BIGINT,
    ADD COLUMN IF NOT EXISTS source_channel VARCHAR(32),
    ADD COLUMN IF NOT EXISTS source_ip INET,
    ADD COLUMN IF NOT EXISTS source_latitude DOUBLE PRECISION,
    ADD COLUMN IF NOT EXISTS source_longitude DOUBLE PRECISION;

UPDATE pix_transactions AS transaction
SET payer_account_id = account.id
FROM accounts AS account
WHERE account.participant IS NULL
  AND account.branch = transaction.payer_branch
  AND account.account_number = transaction.payer_account_number
  AND account.owner_document = upper(translate(transaction.payer_document, '.-/ ', ''));

UPDATE pix_transactions AS transaction
SET payee_account_id = account.id
FROM accounts AS account
WHERE account.participant = transaction.payee_participant
  AND account.branch = transaction.payee_branch
  AND account.account_number = transaction.payee_account_number
  AND account.owner_document = upper(translate(transaction.payee_document, '.-/ ', ''));

UPDATE pix_transactions AS transaction
SET device_id = device.id
FROM devices AS device
WHERE device.identifier = transaction.source_device_id;

UPDATE pix_transactions
SET source_channel = request_payload #>> '{source,channel}',
    source_ip = (request_payload #>> '{source,ip}')::INET,
    source_latitude = (request_payload #>> '{source,geolocation,latitude}')::DOUBLE PRECISION,
    source_longitude = (request_payload #>> '{source,geolocation,longitude}')::DOUBLE PRECISION;

ALTER TABLE pix_transactions
    ALTER COLUMN external_id TYPE VARCHAR(128),
    ALTER COLUMN canonicalization_version TYPE VARCHAR(32),
    ALTER COLUMN source_ip TYPE INET USING source_ip::INET,
    ALTER COLUMN payer_account_id SET NOT NULL,
    ALTER COLUMN payee_account_id SET NOT NULL,
    ALTER COLUMN device_id SET NOT NULL,
    ALTER COLUMN source_channel SET NOT NULL,
    ALTER COLUMN source_ip SET NOT NULL;

ALTER TABLE pix_analyses
    DROP CONSTRAINT IF EXISTS ck_pix_analyses_status,
    DROP CONSTRAINT IF EXISTS pix_analyses_status_check,
    ALTER COLUMN status TYPE pix_analysis_status
        USING status::pix_analysis_status,
    ALTER COLUMN policy_version TYPE VARCHAR(64);

ALTER TABLE pix_transactions
    ADD CONSTRAINT fk_pix_transactions_payer_account
        FOREIGN KEY (payer_account_id) REFERENCES accounts(id) ON DELETE RESTRICT,
    ADD CONSTRAINT fk_pix_transactions_payee_account
        FOREIGN KEY (payee_account_id) REFERENCES accounts(id) ON DELETE RESTRICT,
    ADD CONSTRAINT fk_pix_transactions_device
        FOREIGN KEY (device_id) REFERENCES devices(id) ON DELETE RESTRICT,
    ADD CONSTRAINT ck_pix_transactions_payload_object
        CHECK (jsonb_typeof(request_payload) = 'object'),
    ADD CONSTRAINT ck_pix_transactions_channel_not_blank
        CHECK (btrim(source_channel) <> ''),
    ADD CONSTRAINT ck_pix_transactions_geolocation_pair
        CHECK ((source_latitude IS NULL) = (source_longitude IS NULL)),
    ADD CONSTRAINT ck_pix_transactions_latitude_range
        CHECK (source_latitude IS NULL OR source_latitude BETWEEN -90 AND 90),
    ADD CONSTRAINT ck_pix_transactions_longitude_range
        CHECK (source_longitude IS NULL OR source_longitude BETWEEN -180 AND 180);

DROP INDEX IF EXISTS ix_pix_transactions_payer_received_at;
DROP INDEX IF EXISTS ix_pix_transactions_payee_received_at;
DROP INDEX IF EXISTS ix_pix_transactions_device_received_at;
DROP INDEX IF EXISTS ix_pix_transactions_source_ip_received_at;

CREATE INDEX ix_pix_transactions_payer_received_at
    ON pix_transactions (payer_account_id, received_at);
CREATE INDEX ix_pix_transactions_payee_received_at
    ON pix_transactions (payee_account_id, received_at);
CREATE INDEX ix_pix_transactions_device_received_at
    ON pix_transactions (device_id, received_at);
CREATE INDEX ix_pix_transactions_source_ip_received_at
    ON pix_transactions (source_ip, received_at);

ALTER TABLE pix_transactions
    DROP COLUMN payer_document,
    DROP COLUMN payer_branch,
    DROP COLUMN payer_account_number,
    DROP COLUMN payee_participant,
    DROP COLUMN payee_branch,
    DROP COLUMN payee_account_number,
    DROP COLUMN payee_document,
    DROP COLUMN source_device_id;

COMMIT;
